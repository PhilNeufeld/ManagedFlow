"""
Build the ManagedFlow user manual from docs/manual_source.md.

    python docs/build_manual.py
        Generic edition (fictional example household) -- safe for GitHub:
        docs/ManagedFlow_Manual.docx and docs/USER_MANUAL.md

    python docs/build_manual.py data/MyPlan.json
        Private edition with your portfolio's examples and data/MyPlan_tasks.md:
        outputs/ManagedFlow_Manual_MyPlan.docx (outputs/ is kept off GitHub)

Needs python-docx (pip install python-docx). Open the .docx in Word, right-click
the contents and choose Update Field; File > Save As > PDF for a PDF.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import example_data  # noqa: E402
import manual  # noqa: E402
import storage  # noqa: E402


def build_generic() -> None:
    p = example_data.build_example_portfolio()
    p.apply_event_dates()
    blocks = manual.build_blocks(p)
    (ROOT / "docs" / "USER_MANUAL.md").write_text(
        "<!-- Generated by docs/build_manual.py from docs/manual_source.md. Edit that file, not this one. -->\n\n"
        "# ManagedFlow User Manual\n\n" + manual.to_markdown(blocks), encoding="utf-8")
    out = ROOT / "docs" / "ManagedFlow_Manual.docx"
    manual.write_docx(blocks, out, edition="Generic (fictional example household)",
                      subtitle="Examples use the fictional Alex & Sam household.")
    print(f"Wrote {out} and docs/USER_MANUAL.md")


def build_private(portfolio_path: Path) -> None:
    p = storage.load_portfolio(portfolio_path)
    tasks = portfolio_path.with_name(f"{portfolio_path.stem}_tasks.md")
    blocks = manual.build_blocks(p, private=True, tasks_path=tasks)
    out = ROOT / "outputs" / f"ManagedFlow_Manual_{portfolio_path.stem}.docx"
    out.parent.mkdir(exist_ok=True)
    manual.write_docx(blocks, out, edition=f"Private -- {p.household.name or portfolio_path.stem}",
                      subtitle=f"Examples use {portfolio_path.name}. Contains your data: keep it private.")
    print(f"Wrote {out} (private: outputs/ is kept off GitHub)")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        build_private(Path(sys.argv[1]))
    else:
        build_generic()
